// Generates the outline data for the service area map from voivodeship boundaries.
//
// Source data: wojewodztwa-medium.geojson from https://github.com/ppatrzyk/polska-geojson
// (boundaries from the state register PRG, GUGiK). The GeoJSON is not kept in the repository.
//
// Usage: node scripts/build-service-map.mjs path/to/wojewodztwa-medium.geojson
// Output: src/content/serviceMapGeometry.ts

import { readFileSync, writeFileSync } from "node:fs";

const [input] = process.argv.slice(2);
if (!input) {
  console.error("Usage: node scripts/build-service-map.mjs path/to/wojewodztwa-medium.geojson");
  process.exit(1);
}

// Map frame in degrees: Pomerania with the Hel peninsula, the Vistula delta and Elbląg. It stops short of
// the Russian border, which the source data does not contain.
const bounds = { lonMin: 16.9, lonMax: 19.65, latMin: 53.5, latMax: 54.97 };
const width = 1000;
// Equirectangular projection scaled by cos(latitude) at the centre of the frame:
// at this size the distortion stays well under one percent.
const lat0 = (bounds.latMin + bounds.latMax) / 2;
const kx = Math.cos((lat0 * Math.PI) / 180);
const scale = width / ((bounds.lonMax - bounds.lonMin) * kx);
const height = Math.round((bounds.latMax - bounds.latMin) * scale);

const project = ([lon, lat]) => [(lon - bounds.lonMin) * kx * scale, (bounds.latMax - lat) * scale];

// Douglas–Peucker simplification in screen units.
const tolerance = 0.6;
const perpendicular = ([px, py], [ax, ay], [bx, by]) => {
  const dx = bx - ax;
  const dy = by - ay;
  const length = Math.hypot(dx, dy);
  if (length === 0) return Math.hypot(px - ax, py - ay);
  return Math.abs(dy * px - dx * py + bx * ay - by * ax) / length;
};
const simplify = (points) => {
  if (points.length < 3) return points;
  let maxDistance = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const distance = perpendicular(points[i], points[0], points.at(-1));
    if (distance > maxDistance) {
      maxDistance = distance;
      index = i;
    }
  }
  if (maxDistance <= tolerance) return [points[0], points.at(-1)];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
};

// Rings are clipped to the frame plus a small pad (Sutherland–Hodgman), so neighbouring voivodeships
// contribute only the part that is actually on the map.
const pad = 12;
const edges = [
  { inside: ([x]) => x >= -pad, cross: (a, b) => lerpAt(a, b, 0, -pad) },
  { inside: ([x]) => x <= width + pad, cross: (a, b) => lerpAt(a, b, 0, width + pad) },
  { inside: ([, y]) => y >= -pad, cross: (a, b) => lerpAt(a, b, 1, -pad) },
  { inside: ([, y]) => y <= height + pad, cross: (a, b) => lerpAt(a, b, 1, height + pad) },
];
function lerpAt(a, b, axis, value) {
  const t = (value - a[axis]) / (b[axis] - a[axis]);
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
}
const clip = (points) =>
  edges.reduce((ring, edge) => {
    const output = [];
    ring.forEach((current, i) => {
      const previous = ring.at(i - 1);
      if (edge.inside(current)) {
        if (!edge.inside(previous)) output.push(edge.cross(previous, current));
        output.push(current);
      } else if (edge.inside(previous)) {
        output.push(edge.cross(previous, current));
      }
    });
    return output;
  }, points);

const round = (value) => Math.round(value * 10) / 10;
const ringToPath = (ring) => {
  const clipped = clip(ring.map(project));
  if (clipped.length < 3) return "";
  const points = simplify([...clipped, clipped[0]]);
  return `M${points.map(([x, y]) => `${round(x)} ${round(y)}`).join("L")}Z`;
};

const geojson = JSON.parse(readFileSync(input, "utf8"));
const regions = [];

for (const feature of geojson.features) {
  const { type, coordinates } = feature.geometry;
  const polygons = type === "Polygon" ? [coordinates] : coordinates;
  const d = polygons.flat().map(ringToPath).join("");
  if (d === "") continue;
  regions.push({ name: feature.properties.nazwa, d });
}

const source = `// Generated by scripts/build-service-map.mjs. Do not edit by hand.
// Boundaries: PRG (GUGiK) via github.com/ppatrzyk/polska-geojson.

export const serviceMapFrame = ${JSON.stringify({ ...bounds, lat0, kx, scale, width, height }, null, 2)};

export const serviceMapRegions: { name: string; d: string }[] = ${JSON.stringify(regions, null, 2)};
`;

writeFileSync("src/content/serviceMapGeometry.ts", source);
console.log(
  `Wrote ${regions.length} regions, ${width}×${height}, ${Math.round(source.length / 1024)} KB`,
);
